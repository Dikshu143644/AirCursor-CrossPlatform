class HardwareRegistry:
    """Manages the catalog of all 5 physical remote device profiles."""

    def __init__(self):
        self._profiles: Dict[HardwareDeviceType, BaseHardwareProfile] = {
            HardwareDeviceType.AIRRING_PRO: AirRingProProfile(),
            HardwareDeviceType.AIRWAND_ELITE: AirWandEliteProfile(),
            HardwareDeviceType.AIRPEBBLE_TOUCH: AirPebbleTouchProfile(),
            HardwareDeviceType.AIRCLIP_MINI: AirClipMiniProfile(),
            HardwareDeviceType.AIRDECK_CONTROLLER: AirDeckControllerProfile(),
        }
        self._active_type: HardwareDeviceType = HardwareDeviceType.AIRRING_PRO
        self._listeners: List[Callable[[HardwareTelemetryEvent], None]] = []

    def get_profile(self, dev_type: HardwareDeviceType) -> BaseHardwareProfile:
        """Retrieve profile by device type."""
        return self._profiles[dev_type]

    def list_all_profiles(self) -> List[BaseHardwareProfile]:
        """Return all 5 hardware profiles in sequence."""
        return list(self._profiles.values())

    @property
    def active_profile(self) -> BaseHardwareProfile:
        """Get currently selected hardware companion profile."""
        return self._profiles[self._active_type]

    def set_active_device(self, dev_type: HardwareDeviceType) -> None:
        """Switch active companion device."""
        if dev_type in self._profiles:
            self._active_type = dev_type

    def add_telemetry_listener(self, callback: Callable[[HardwareTelemetryEvent], None]) -> None:
        """Register a callback for telemetry updates."""
        self._listeners.append(callback)

    def dispatch_event(self, event: HardwareTelemetryEvent) -> None:
        """Notify all listeners of a new hardware event."""
        for cb in self._listeners:
            try:
                cb(event)
            except Exception:
                pass


class HardwarePacketEncoder:
    """Encodes synthetic packets for hardware testing, calibration, and emulation."""

    @staticmethod
    def encode_airring_pro(
        seq: int = 1,
        pitch: float = 0.0,
        roll: float = 0.0,
        opt_x: int = 0,
        opt_y: int = 0,
        bezel_delta: int = 0,
        primary_click: bool = False,
        secondary_click: bool = False,
        battery_pct: int = 95,
        charging: bool = False
    ) -> bytes:
        flags = (0x01 if primary_click else 0) | (0x02 if secondary_click else 0) | (0x80 if charging else 0)
        p_raw = int(pitch * 100)
        r_raw = int(roll * 100)
        inner = struct.pack(
            ">hhbbbBB",
            p_raw, r_raw,
            max(-128, min(127, opt_x)),
            max(-128, min(127, opt_y)),
            max(-128, min(127, bezel_delta)),
            flags,
            max(0, min(100, battery_pct))
        )
        packet_pre = bytes([0xA1, 1, seq & 0xFF]) + inner
        chk = HardwarePacketDecoder.calculate_checksum(packet_pre)
        return packet_pre + bytes([chk])

    @staticmethod
    def encode_airwand_elite(
        seq: int = 1,
        yaw: float = 0.0,
        pitch: float = 0.0,
        roll: float = 0.0,
        thumb_x: int = 0,
        thumb_y: int = 0,
        trigger_force: float = 0.0,
        squeeze_force: float = 0.0,
        battery_pct: int = 90
    ) -> bytes:
        # Approximate quaternion from Euler
        cy = math.cos(math.radians(yaw * 0.5))
        sy = math.sin(math.radians(yaw * 0.5))
        cp = math.cos(math.radians(pitch * 0.5))
        sp = math.sin(math.radians(pitch * 0.5))
        cr = math.cos(math.radians(roll * 0.5))
        sr = math.sin(math.radians(roll * 0.5))

        w = int((cr * cp * cy + sr * sp * sy) * 10000)
        x = int((sr * cp * cy - cr * sp * sy) * 10000)
        y = int((cr * sp * cy + sr * cp * sy) * 10000)
        z = int((cr * cp * sy - sr * sp * cy) * 10000)

        tf_byte = int(max(0.0, min(1.0, trigger_force)) * 255)
        sf_byte = int(max(0.0, min(1.0, squeeze_force)) * 255)
        flags = (0x01 if tf_byte > 20 else 0) | (0x02 if sf_byte > 50 else 0)

        inner = struct.pack(
            ">hhhhbbBBBB",
            w, x, y, z,
            max(-128, min(127, thumb_x)),
            max(-128, min(127, thumb_y)),
            tf_byte, sf_byte, flags,
            max(0, min(100, battery_pct))
        )
        packet_pre = bytes([0xA2, 2, seq & 0xFF]) + inner
        chk = HardwarePacketDecoder.calculate_checksum(packet_pre)
        return packet_pre + bytes([chk])

    @staticmethod
    def encode_airpebble_touch(
        seq: int = 1,
        opt_dx: int = 0,
        opt_dy: int = 0,
        dial_delta: int = 0,
        touch_x: int = 128,
        touch_y: int = 128,
        touch_pressure: float = 0.0,
        primary_click: bool = False,
        secondary_click: bool = False,
        battery_pct: int = 98
    ) -> bytes:
        flags = (0x01 if primary_click else 0) | (0x02 if secondary_click else 0)
        press_byte = int(max(0.0, min(1.0, touch_pressure)) * 255)
        inner = struct.pack(
            ">hhbBBBBB",
            opt_dx, opt_dy,
            max(-128, min(127, dial_delta)),
            touch_x & 0xFF, touch_y & 0xFF,
            press_byte, flags,
            max(0, min(100, battery_pct))
        )
        packet_pre = bytes([0xA3, 3, seq & 0xFF]) + inner
        chk = HardwarePacketDecoder.calculate_checksum(packet_pre)
        return packet_pre + bytes([chk])

    @staticmethod
    def encode_airclip_mini(
        seq: int = 1,
        pitch: float = 0.0,
        roll: float = 0.0,
        is_muted: bool = False,
        tap_count: int = 0,
        battery_pct: int = 88
    ) -> bytes:
        flags = 0x01 if is_muted else 0x00
        p_raw = int(pitch * 100)
        r_raw = int(roll * 100)
        inner = struct.pack(
            ">hhBBB",
            p_raw, r_raw,
            flags,
            tap_count & 0xFF,
            max(0, min(100, battery_pct))
        )
        packet_pre = bytes([0xA4, 4, seq & 0xFF]) + inner
        chk = HardwarePacketDecoder.calculate_checksum(packet_pre)
        return packet_pre + bytes([chk])

    @staticmethod
    def encode_airdeck_controller(
        seq: int = 1,
        track_x: int = 0,
        track_y: int = 0,
        force: float = 0.0,
        gyro_x: int = 0,
        gyro_y: int = 0,
        l1: bool = False,
        r1: bool = False,
        battery_pct: int = 92
    ) -> bytes:
        buttons = (0x01 if l1 else 0) | (0x02 if r1 else 0)
        force_byte = int(max(0.0, min(1.0, force)) * 255)
        inner = struct.pack(
            ">bbBhhBB",
            max(-128, min(127, track_x)),
            max(-128, min(127, track_y)),
            force_byte,
            gyro_x, gyro_y,
            buttons,
            max(0, min(100, battery_pct))
        )
        packet_pre = bytes([0xA5, 5, seq & 0xFF]) + inner
        chk = HardwarePacketDecoder.calculate_checksum(packet_pre)
        return packet_pre + bytes([chk])


