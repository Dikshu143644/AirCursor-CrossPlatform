# BINARY TELEMETRY PROTOCOL & DECODER
# ============================================================================

class HardwarePacketDecoder:
    """
    Decodes high-throughput binary telemetry packets (100Hz-1000Hz) transmitted
    by any of the 5 AirCursor physical remote devices over BLE 5.3 GATT,
    2.4GHz USB Dongle, or Serial/HID endpoints.

    Packet Structure:
      Byte 0:     Magic Header (0xA1..0xA5 matching Device Type)
      Byte 1:     Device Type ID (0x01..0x05)
      Byte 2:     Packet Sequence Counter (0..255)
      Byte 3-N:   Device-specific payload
      Last Byte:  XOR Checksum of all preceding bytes
    """

    MAGIC_HEADERS = {
        HardwareDeviceType.AIRRING_PRO: 0xA1,
        HardwareDeviceType.AIRWAND_ELITE: 0xA2,
        HardwareDeviceType.AIRPEBBLE_TOUCH: 0xA3,
        HardwareDeviceType.AIRCLIP_MINI: 0xA4,
        HardwareDeviceType.AIRDECK_CONTROLLER: 0xA5,
    }

    @staticmethod
    def calculate_checksum(data: bytes) -> int:
        """Calculate XOR checksum over payload bytes."""
        chk = 0
        for b in data:
            chk ^= b
        return chk & 0xFF

    @classmethod
    def decode(cls, raw_bytes: bytes) -> Optional[HardwareTelemetryEvent]:
        """
        Parse raw bytes and return a HardwareTelemetryEvent, or None if invalid.
        """
        if not raw_bytes or len(raw_bytes) < 6:
            return None

        # Verify checksum
        payload, expected_checksum = raw_bytes[:-1], raw_bytes[-1]
        if cls.calculate_checksum(payload) != expected_checksum:
            return None

        magic = payload[0]
        dev_id = payload[1]
        seq = payload[2]

        try:
            device_type = HardwareDeviceType(dev_id)
        except ValueError:
            return None

        if cls.MAGIC_HEADERS.get(device_type) != magic:
            return None

        now = time.time()

        if device_type == HardwareDeviceType.AIRRING_PRO:
            # 13-byte packet:
            # [Magic(0xA1), Dev(1), Seq, Pitch(h), Roll(h), OptX(b), OptY(b), BezelDelta(b), Flags(B), Batt(B), Checksum]
            if len(raw_bytes) < 13:
                return None
            pitch_raw, roll_raw, opt_x, opt_y, bezel_delta, flags, batt = struct.unpack(
                ">hhbbbBB", raw_bytes[3:12]
            )
            pitch = pitch_raw / 100.0
            roll = roll_raw / 100.0
            primary = bool(flags & 0x01)
            secondary = bool(flags & 0x02)
            charging = bool(flags & 0x80)

            return HardwareTelemetryEvent(
                device_type=device_type,
                timestamp=now,
                sequence=seq,
                pitch=pitch,
                roll=roll,
                delta_x=float(opt_x),
                delta_y=float(opt_y),
                dial_delta=float(bezel_delta),
                primary_click=primary,
                secondary_click=secondary,
                battery_pct=batt,
                charging=charging,
                raw_flags=flags,
            )

        elif device_type == HardwareDeviceType.AIRWAND_ELITE:
            # 18-byte packet:
            # [Magic(0xA2), Dev(2), Seq, QuatW(h), QuatX(h), QuatY(h), QuatZ(h), ThumbX(b), ThumbY(b), TrigForce(B), SqueezeForce(B), Flags(B), Batt(B), Checksum]
            if len(raw_bytes) < 18:
                return None
            qw, qx, qy, qz, tx, ty, tf, sf, flags, batt = struct.unpack(
                ">hhhhbbBBBB", raw_bytes[3:17]
            )
            # Convert quaternion (int16 / 10000.0) to Euler yaw, pitch, roll
            w = qw / 10000.0
            x = qx / 10000.0
            y = qy / 10000.0
            z = qz / 10000.0

            # Euler angles in degrees
            sinr_cosp = 2.0 * (w * x + y * z)
            cosr_cosp = 1.0 - 2.0 * (x * x + y * y)
            roll = math.degrees(math.atan2(sinr_cosp, cosr_cosp))

            sinp = 2.0 * (w * y - z * x)
            pitch = math.degrees(math.asin(max(-1.0, min(1.0, sinp))))

            siny_cosp = 2.0 * (w * z + x * y)
            cosy_cosp = 1.0 - 2.0 * (y * y + z * z)
            yaw = math.degrees(math.atan2(siny_cosp, cosy_cosp))

            trig_pressed = (tf > 20) or bool(flags & 0x01)
            sq_pressed = (sf > 50) or bool(flags & 0x02)

            return HardwareTelemetryEvent(
                device_type=device_type,
                timestamp=now,
                sequence=seq,
                yaw=yaw,
                pitch=pitch,
                roll=roll,
                delta_x=float(tx),
                delta_y=float(ty),
                trigger_pressed=trig_pressed,
                squeeze_pressed=sq_pressed,
                trigger_force=tf / 255.0,
                squeeze_force=sf / 255.0,
                primary_click=trig_pressed,
                secondary_click=sq_pressed,
                battery_pct=batt,
                charging=bool(flags & 0x80),
                raw_flags=flags,
            )

        elif device_type == HardwareDeviceType.AIRPEBBLE_TOUCH:
            # 14-byte packet:
            # [Magic(0xA3), Dev(3), Seq, OptDx(h), OptDy(h), DialDelta(b), TouchX(B), TouchY(B), TouchPressure(B), Flags(B), Batt(B), Checksum]
            if len(raw_bytes) < 14:
                return None
            opt_dx, opt_dy, dial_delta, tx, ty, press, flags, batt = struct.unpack(
                ">hhbBBBBB", raw_bytes[3:13]
            )
            return HardwareTelemetryEvent(
                device_type=device_type,
                timestamp=now,
                sequence=seq,
                delta_x=float(opt_dx),
                delta_y=float(opt_dy),
                dial_delta=float(dial_delta),
                touch_pressure=press / 255.0,
                primary_click=bool(flags & 0x01),
                secondary_click=bool(flags & 0x02),
                middle_click=bool(flags & 0x04),
                battery_pct=batt,
                charging=bool(flags & 0x80),
                raw_flags=flags,
            )

        elif device_type == HardwareDeviceType.AIRCLIP_MINI:
            # 11-byte packet:
            # [Magic(0xA4), Dev(4), Seq, Pitch(h), Roll(h), Flags(B), TapCount(B), Batt(B), Checksum]
            if len(raw_bytes) < 11:
                return None
            pitch_raw, roll_raw, flags, tap_cnt, batt = struct.unpack(
                ">hhBBB", raw_bytes[3:10]
            )
            is_muted = bool(flags & 0x01)
            tap_click = (tap_cnt > 0) or bool(flags & 0x02)

            return HardwareTelemetryEvent(
                device_type=device_type,
                timestamp=now,
                sequence=seq,
                pitch=pitch_raw / 100.0,
                roll=roll_raw / 100.0,
                mute_switch_active=is_muted,
                primary_click=tap_click and not is_muted,
                battery_pct=batt,
                charging=bool(flags & 0x80),
                raw_flags=flags,
            )

        elif device_type == HardwareDeviceType.AIRDECK_CONTROLLER:
            # 13-byte packet:
            # [Magic(0xA5), Dev(5), Seq, TrackX(b), TrackY(b), Force(B), GyroX(h), GyroY(h), Buttons(B), Batt(B), Checksum]
            if len(raw_bytes) < 13:
                return None
            tr_x, tr_y, force, gx, gy, buttons, batt = struct.unpack(
                ">bbBhhBB", raw_bytes[3:12]
            )
            l1 = bool(buttons & 0x01)
            r1 = bool(buttons & 0x02)
            press_click = force > 30

            return HardwareTelemetryEvent(
                device_type=device_type,
                timestamp=now,
                sequence=seq,
                delta_x=float(tr_x),
                delta_y=float(tr_y),
                touch_pressure=force / 255.0,
                primary_click=l1 or press_click,
                secondary_click=r1,
                battery_pct=batt,
                charging=bool(buttons & 0x80),
                raw_flags=buttons,
            )

        return None


