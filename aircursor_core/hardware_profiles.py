"""
AirCursor Hardware Profiles & Binary Telemetry Engine
======================================================
Defines physical specifications, control surfaces, sensor payloads,
binary BLE/USB telemetry decoders, and event dispatchers for all 5 physical
AirCursor remote hardware products:

  01. AirRing Pro        - Index-Finger Smart Ring (8.8g)
  02. AirWand Elite       - Ergonomic Air Baton (52g)
  03. AirPebble Touch     - River-Stone Palm/Desk Puck (64g)
  04. AirClip Mini        - Glasses / Collar Lapel Clip (14g)
  05. AirDeck Controller  - Handheld Asymmetric Thumb-Deck (68g)
"""

from __future__ import annotations

import enum
