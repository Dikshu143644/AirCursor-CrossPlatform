class HardwareDeviceType(enum.IntEnum):
    """Enumeration of the 5 AirCursor physical products."""
    AIRRING_PRO = 1
    AIRWAND_ELITE = 2
    AIRPEBBLE_TOUCH = 3
    AIRCLIP_MINI = 4
    AIRDECK_CONTROLLER = 5


class ConnectionTransport(enum.Enum):
    """Physical and wireless connection transports."""
    BLE_5_3_GATT = "BLE 5.3 LE"
    RF_2_4GHZ_DONGLE = "2.4GHz Proprietary Low-Latency"
    USB_C_WIRED = "USB-C High-Speed HID"
    WEBSOCKET_EMULATION = "WebSocket Virtual Emulation"


@dataclass
class HardwareTelemetryEvent:
    """Standardized event generated by any of the 5 hardware products."""
    device_type: HardwareDeviceType
    timestamp: float
    sequence: int
    # Orientation / Rotation (deg)
    yaw: float = 0.0
    pitch: float = 0.0
    roll: float = 0.0
    # Relative Motion (counts / pixels)
    delta_x: float = 0.0
    delta_y: float = 0.0
    delta_z: float = 0.0
    # Bezel / Rotary dial deltas
    dial_delta: float = 0.0
    # Button states (bitmask or booleans)
    primary_click: bool = False
    secondary_click: bool = False
    middle_click: bool = False
    trigger_pressed: bool = False
    squeeze_pressed: bool = False
    mute_switch_active: bool = False
    # Analog inputs (0.0 to 1.0)
    trigger_force: float = 0.0
    squeeze_force: float = 0.0
    touch_pressure: float = 0.0
    # Telemetry state
    battery_pct: int = 100
    charging: bool = False
    rssi_dbm: int = -45
    raw_flags: int = 0


@dataclass
class BaseHardwareProfile:
    """Base configuration profile for an AirCursor physical product."""
    device_type: HardwareDeviceType
    model_name: str
    form_factor: str
    mass_grams: float
    dimensions_mm: Tuple[float, float, float]  # Length, Width, Height
    primary_controls: List[str]
    sensor_suite: List[str]
    battery_capacity_mah: int
    battery_life_hours: float
    cad_files: Dict[str, str] = field(default_factory=dict)
    
    # Calibration & tuning parameters
    cursor_sensitivity: float = 1.0
    scroll_sensitivity: float = 1.0
    deadzone_threshold: float = 0.02
    haptic_enabled: bool = True
    invert_y: bool = False

    def to_dict(self) -> Dict[str, Any]:
        """Serialize profile to JSON-compatible dictionary."""
        return {
            "device_type": self.device_type.value,
            "model_name": self.model_name,
            "form_factor": self.form_factor,
            "mass_grams": self.mass_grams,
            "dimensions_mm": list(self.dimensions_mm),
            "primary_controls": self.primary_controls,
            "sensor_suite": self.sensor_suite,
            "battery_capacity_mah": self.battery_capacity_mah,
            "battery_life_hours": self.battery_life_hours,
            "cad_files": self.cad_files,
            "cursor_sensitivity": self.cursor_sensitivity,
            "scroll_sensitivity": self.scroll_sensitivity,
            "deadzone_threshold": self.deadzone_threshold,
            "haptic_enabled": self.haptic_enabled,
            "invert_y": self.invert_y,
        }


